-- Mesma estrutura, em sintaxe H2 (banco em memoria usado apenas nos testes automatizados)

CREATE TABLE usuarios (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(100) NOT NULL,
    email   VARCHAR(120) NOT NULL,
    senha   VARCHAR(100) NOT NULL,
    perfil  VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('ADMIN', 'OPERADOR'))
);

CREATE TABLE pontos_coleta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(100)   NOT NULL,
    endereco       VARCHAR(200)   NOT NULL,
    bairro         VARCHAR(80)    NOT NULL,
    tipo_residuo   VARCHAR(20)    NOT NULL,
    capacidade_kg  NUMERIC(10, 2) NOT NULL,
    criado_em      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_pontos_tipo CHECK (tipo_residuo IN ('PLASTICO', 'PAPEL', 'VIDRO', 'METAL', 'ORGANICO', 'ELETRONICO'))
);

CREATE TABLE coletas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_coleta_id  BIGINT         NOT NULL,
    data_coleta      DATE           NOT NULL,
    quantidade_kg    NUMERIC(10, 2) NOT NULL,
    status           VARCHAR(20)    NOT NULL,
    observacao       VARCHAR(255),
    CONSTRAINT fk_coletas_ponto FOREIGN KEY (ponto_coleta_id) REFERENCES pontos_coleta (id),
    CONSTRAINT ck_coletas_status CHECK (status IN ('AGENDADA', 'CONCLUIDA', 'CANCELADA'))
);

CREATE INDEX idx_coletas_ponto ON coletas (ponto_coleta_id);
